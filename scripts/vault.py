MOMENT_TOKENS = [("YYYY", "%Y"), ("GGGG", "%G"), ("MMMM", "%B"), ("MM", "%m"),
                 ("DD", "%d"), ("dddd", "%A"), ("HH", "%H"), ("mm", "%M"),
                 ("WW", "%V"), ("ww", "%V"), ("[W]", "W")]


def render_template(text: str, title: str, when: dt.datetime, cfg: Config) -> str:
    """Expand Obsidian-style {{date:...}} / {{title}} placeholders.

    Templates quote every date placeholder so the file is valid YAML *before*
    rendering (Obsidian's own Templates plugin inserts into a live note). Fields
    the schema says are unquoted get unquoted here, after substitution."""
    def fmt(m):
        pattern = m.group(1)
        for token, py in MOMENT_TOKENS:
            pattern = pattern.replace(token, py)
        return when.strftime(pattern)

    text = re.sub(r"\{\{(?:date|time):([^}]+)\}\}", fmt, text)
    text = text.replace("{{date}}", when.strftime("%Y-%m-%d"))
    text = text.replace("{{time}}", when.strftime("%H:%M"))
    text = text.replace("{{title}}", title)
    text = text.replace("{{vault}}", cfg.name)
    unquoted = "|".join(sorted(cfg.dates_unquoted))
    return re.sub(rf'^({unquoted}): "(\d{{4}}-\d{{2}}-\d{{2}})"$', r"\1: \2",
                  text, flags=re.MULTILINE)


def resolve_new_kind(cfg: Config, kind: str):
    """`new` accepts a type name (`project`) or a variant name (`decision`, `paper`)."""
    if kind in cfg.types:
        t = cfg.types[kind]
        if t.variants:
            return None, None  # ambiguous: name the variant instead
        return t, None
    variant = cfg.find_variant(kind)
    if variant:
        return cfg.types[variant.parent], variant
    return None, None


def new_note_path(cfg: Config, ntype, variant, title: str, when: dt.datetime) -> Path:
    folder = variant.folder if variant else ntype.folder
    pattern = (variant.filename if variant and variant.filename else ntype.filename)
    safe = slugify(title)
    date = when.date().isoformat()
    if pattern == "daily":
        return VAULT / folder / when.strftime("%Y") / when.strftime("%m") / f"{date}.md"
    if pattern == "week":
        return VAULT / folder / f"{when.strftime('%G-W%V')}.md"
    if pattern == "capture":
        words = " ".join(safe.split()[:8]) or "Capture"
        return VAULT / folder / f"{date} {when.strftime('%H%M')} {words}.md"
    if pattern == "dated":
        return VAULT / folder / f"{date} {safe}.md"
    if pattern == "log":
        return VAULT / folder / f"{date}-{safe.lower().replace(' ', '-')}.md"
    return VAULT / folder / f"{safe}.md"


def apply_sets(cfg: Config, text: str, sets: list[str]) -> str:
    """Apply `--set key=value` to the rendered frontmatter, quoting per the schema."""
    m = fmlib.FRONTMATTER_RE.match(text)
    if not m:
        return text
    block, rest = m.group(1), text[m.end():]
    lines = block.split("\n")
    for item in sets:
        key, _, value = item.partition("=")
        key, value = key.strip(), value.strip()
        if not key:
            continue
        if key in cfg.link_lists:
            parts = [v.strip() for v in value.split(",") if v.strip()]
            rendered = "\n".join(f'  - "[[{fmlib.link_target(v)}]]"' for v in parts)
            new = f"{key}:\n{rendered}" if parts else f"{key}: []"
        elif key in cfg.link_scalars:
            new = f'{key}: "[[{fmlib.link_target(value)}]]"'
        elif key == "tags":
            parts = [v.strip() for v in value.split(",") if v.strip()]
            new = f"{key}: [{', '.join(parts)}]"
        elif key in cfg.dates_unquoted or value[:1] in ('"', "[") or value in ("true", "false"):
            new = f"{key}: {value}"
        elif key in cfg.dates_quoted or " " in value or ":" in value:
            new = f'{key}: "{value}"'
        else:
            new = f"{key}: {value}"
        for i, line in enumerate(lines):
            if re.match(rf"^{re.escape(key)}:", line):
                # Replace the key and any block-list items under it.
                j = i + 1
                while j < len(lines) and lines[j].startswith((" ", "\t")) and lines[j].lstrip().startswith("-"):
                    j += 1
                lines[i:j] = new.split("\n")
                break
        else:
            lines.append(new)
    return "---\n" + "\n".join(lines) + "\n---\n" + rest


def cmd_new(cfg: Config, args) -> int:
    ntype, variant = resolve_new_kind(cfg, args.type)
    if ntype is None:
        known = sorted([n for n, t in cfg.types.items() if not t.variants]
                       + list(cfg.all_variants))
        parent = cfg.types.get(args.type)
        hint = (f"{args.type!r} has variants — name one of: "
                f"{', '.join(sorted(parent.variants))}" if parent
                else f"unknown type {args.type!r}")
        print(f"{hint}.\nKnown: {', '.join(known)}", file=sys.stderr)
        return 2
    if ntype.immutable and not args.force:
        print(f"{ntype.name} notes are written by pipelines, not by hand "
              f"(docs/ingestion.md). Use --force if you are sure.", file=sys.stderr)
        return 2

    when = dt.datetime.now()
    if args.date:
        try:
            when = dt.datetime.combine(dt.date.fromisoformat(args.date), when.time())
        except ValueError:
            print(f"--date must be YYYY-MM-DD, got {args.date!r}", file=sys.stderr)
            return 2

    # Types whose filename is derived from the date name themselves.
    pattern = variant.filename if variant and variant.filename else ntype.filename
    self_naming = pattern in ("daily", "week")
    title = args.title or ((variant.name if variant else ntype.name).title()
                           if self_naming else "")
    if not title:
        print(f"a title is required for `new {args.type}`", file=sys.stderr)
        return 2

    template_name = (variant.template if variant and variant.template else ntype.template)
    if not template_name:
        template_name = f"{variant.name if variant else ntype.name}.md"
    tpl = VAULT / "templates" / template_name
    if not tpl.exists():
        print(f"missing template {rel(tpl)}", file=sys.stderr)
        return 2

    text = render_template(read_text(tpl), title, when, cfg)
    sets = list(args.set or [])
    if variant and ntype.variant_field:
        sets.insert(0, f"{ntype.variant_field}={variant.name}")
    if args.body:
        text = text.rstrip() + "\n\n" + args.body + "\n"
    text = apply_sets(cfg, text, sets)

    # A title that had to be sanitized keeps its pretty form as an alias, so
    # [[Original/Title]] still resolves.
    path = next_free_path(new_note_path(cfg, ntype, variant, title, when))
    if title and slugify(title) != title and "aliases:" not in text:
        text = apply_sets(cfg, text, [f'aliases=["{title}"]'])

    if path.exists() and not args.force:
        print(f"refusing to overwrite {rel(path)}", file=sys.stderr)
        return 2
    atomic_write(path, text)

    issues = linter.lint_file(path, cfg)
    blocking = [i for i in issues if i.blocking]
    print(rel(path), flush=True)
    for issue in blocking:
        print(f"  {issue.level}  {issue.msg}", file=sys.stderr)
    if blocking:
        print("\nFill the fields above, then re-run `vault.py lint <path>`.", file=sys.stderr)
        return 1
    return 0


