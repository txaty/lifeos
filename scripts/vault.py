def cmd_rename(cfg: Config, args) -> int:
    src = Path(args.path)
    if not src.is_absolute():
        src = VAULT / args.path
    if not src.is_file():
        print(f"no such note: {args.path}", file=sys.stderr)
        return 2

    r = rel(src)
    ntype = cfg.type_for_path(r)
    if ntype is None:
        print(f"{r} is not in a content folder", file=sys.stderr)
        return 2
    if ntype.immutable and not args.force:
        print(f"{ntype.name} notes are immutable. Use --force if you must.", file=sys.stderr)
        return 2

    old_stem = src.stem
    prefix = ""
    m = re.match(r"^(\d{4}-\d{2}-\d{2} )", old_stem)
    if m and ntype.filename in ("dated", "capture"):
        prefix = m.group(1)
    new_stem = prefix + slugify(args.new_title)
    if new_stem == old_stem:
        print("name unchanged")
        return 0
    dst = src.with_name(new_stem + ".md")
    if dst.exists():
        print(f"target already exists: {rel(dst)}", file=sys.stderr)
        return 2

    edits: list[tuple[Path, str]] = []
    pattern = re.compile(r"\[\[" + re.escape(old_stem) + r"((?:#|\|)[^\]]*)?\]\]")
    for p in iter_notes(cfg):
        text = read_text(p)
        new_text, n = pattern.subn(lambda mm: f"[[{new_stem}{mm.group(1) or ''}]]", text)
        if n:
            edits.append((p, new_text))

    print(f"{r}  ->  {rel(dst)}")
    print(f"{len(edits)} file(s) contain links to update")
    if args.dry_run:
        for p, _ in edits[:20]:
            print(f"  {rel(p)}")
        print("\n(dry run — nothing written)")
        return 0

    for p, new_text in edits:
        atomic_write(p, new_text)
    src.rename(dst)

    # `title:` follows the filename, and the old name survives as an alias so links
    # from outside the vault — and your own memory — keep resolving.
    text = read_text(dst)
    fm = fmlib.parse(text)
    sets = []
    if "title" in fm:
        sets.append(f"title={args.new_title}")
    if not args.no_alias:
        aliases = [str(a) for a in fmlib.as_list(fm.get("aliases"))]
        old_title = fmlib.unquote(str(fm.get("title", ""))) or old_stem
        for candidate in (old_stem, old_title):
            if candidate and candidate not in aliases and candidate != args.new_title \
                    and not DATE_PREFIX_RE.match(candidate):
                aliases.append(candidate)
        if aliases:
            quoted = ", ".join(chr(34) + a + chr(34) for a in aliases)
            sets.append(f"aliases=[{quoted}]")
    if sets:
        atomic_write(dst, apply_sets(cfg, text, sets))
    print("done. Run `python3 scripts/vault.py check`.")
    return 0


