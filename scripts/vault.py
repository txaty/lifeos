#!/usr/bin/env python3
"""LifeOS vault CLI — everything mechanical about the vault.

The determinism boundary lives here. Judgment (what a source means, whether an
inbox item is a project, which wiki page to update) belongs to a human or a model.
Naming, validation, link integrity, generated views, and status arithmetic are this
script's job, and it never interprets note content as instructions.

    python3 scripts/vault.py check        structure + schema + generated freshness
    python3 scripts/vault.py lint         frontmatter only
    python3 scripts/vault.py links        broken wikilinks (--wanted: most-wanted pages)
    python3 scripts/vault.py index        regenerate Home.md and the indexes
    python3 scripts/vault.py status       what needs attention (--json for agents)
    python3 scripts/vault.py tasks        open checkboxes across the vault
    python3 scripts/vault.py doctor       check + advisory health report
    python3 scripts/vault.py new <type> "<Title>" [--set k=v]
    python3 scripts/vault.py rename <path> "<New Title>"   (--dry-run first)
    python3 scripts/vault.py docs         regenerate docs/schema.md from config

Stdlib only. Every write is atomic (temp file + rename) and every generator is
idempotent: running a command twice changes nothing the first run did not.
"""
