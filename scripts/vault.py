def collect_status(cfg: Config, today: dt.date) -> dict:
    """Every fact the weekly review and the dashboard need, computed once."""
    st: dict = {}

    itype = cfg.types.get("inbox")
    inbox = list(iter_notes(cfg, [itype.folder])) if itype else []
    ages = [days_since(p.name[:10], today) for p in inbox]
    ages = [a for a in ages if a is not None]
    st["inbox"] = {"count": len(inbox), "oldest_days": max(ages) if ages else None,
                   "files": [rel(p) for p in inbox[:20]]}

    ptype = cfg.types["project"]
    by_status: Counter = Counter()
    stale, old_ideas, awaiting = [], [], []
    for p, fm in _collect(cfg, ptype.folder):
        status = fm_str(fm.get("status")) or "active"
        by_status[status] += 1
        age = days_since(fm.get("updated"), today)
        if status == "active" and age is not None and age > cfg.stale_active_days:
            stale.append(p.stem)
        if status == "idea" and age is not None and age > cfg.stale_idea_days:
            old_ideas.append(p.stem)
        if status == "done":
            awaiting.append(p.stem)
    st["projects"] = {"by_status": dict(by_status), "stale": sorted(stale),
                      "old_ideas": sorted(old_ideas), "awaiting_archive": sorted(awaiting)}

    atype = cfg.types.get("area")
    areas = list(_collect(cfg, atype.folder)) if atype else []
    st["areas"] = {"active": sum(1 for _, fm in areas if fm_str(fm.get("status")) == "active"),
                   "dormant": sum(1 for _, fm in areas if fm_str(fm.get("status")) == "dormant")}

    due = []
    dec = cfg.find_variant("decision")
    if dec:
        for p, fm in _collect(cfg, dec.folder):
            if fm_str(fm.get("outcome")) != "unknown" or fm_str(fm.get("status")) == "superseded":
                continue
            deadline = fm.get("review_on") or fm.get("date")
            age = days_since(deadline, today)
            if age is not None and age >= (0 if fm.get("review_on") else cfg.decision_review_days):
                due.append(p.stem)
    st["decisions"] = {"due": sorted(due)}

    wtype = cfg.types["wiki"]
    week_ago = today - dt.timedelta(days=7)
    wiki = [(p, fm) for p, fm in _collect(cfg, wtype.folder)
            if not rel(p).startswith(cfg.wiki_domain_dir + "/")]
    new_week = [p.stem for p, fm in wiki
                if (d := parse_date(fm.get("created"))) and d >= week_ago]
    st["wiki"] = {"total": len(wiki), "created_this_week": sorted(new_week)}

    stype = cfg.types.get("source")
    st["sources"] = {"total": sum(1 for _ in _collect(cfg, stype.folder))} if stype else {"total": 0}
    st["people"] = sum(1 for _ in _collect(cfg, cfg.types["person"].folder)) if "person" in cfg.types else 0
    st["meetings"] = sum(1 for _ in _collect(cfg, cfg.types["meeting"].folder)) if "meeting" in cfg.types else 0

    tasks = collect_tasks(cfg, today)
    st["tasks"] = {"open": sum(len(v) for v in tasks.values()), "notes": len(tasks)}

    ltype = cfg.types.get("log")
    cadence: dict[str, int] = {}
    if ltype:
        for p in iter_notes(cfg, [ltype.folder]):
            m = re.match(r"^(\d{4}-\d{2}-\d{2})-(.+)\.md$", p.name)
            if not m:
                continue
            age = days_since(m.group(1), today)
            if age is not None:
                cadence[m.group(2)] = min(cadence.get(m.group(2), age), age)
    st["cadence"] = cadence
    return st


def collect_tasks(cfg: Config, today: dt.date, days: int = 30) -> dict[str, list[str]]:
    """Open checkboxes, from the notes that own them. Tasks are never their own note,
    so this is the only place they are ever aggregated."""
    out: dict[str, list[str]] = {}
    folders = [t.folder for name, t in cfg.types.items()
               if name in ("project", "area", "meeting", "daily")]
    cutoff = today - dt.timedelta(days=days)
    for p in iter_notes(cfg, folders):
        r = rel(p)
        if p.name.startswith("_"):
            continue
        if r.startswith(cfg.types["daily"].folder + "/"):
            d = parse_date(p.stem)
            if d and d < cutoff:
                continue
        ptype = cfg.type_for_path(r)
        if ptype and ptype.archive_folder and r.startswith(ptype.archive_folder + "/"):
            continue
        found = TASK_OPEN_RE.findall(fmlib.strip_code(read_text(p)))
        if found:
            out[r] = [t.strip() for t in found]
    return out


