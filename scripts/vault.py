GENERATED_MARK = ("<!-- GENERATED by `python3 scripts/vault.py index` — "
                  "edit the source notes, not this file -->")

# Characters that break `[[wikilinks]]` or are illegal on some filesystems.
HARD_ILLEGAL = set('/\\|')
SOFT_ILLEGAL = set('#^[]:*?"<>')

NAME_PATTERNS = {
    "dated": re.compile(r"^\d{4}-\d{2}-\d{2} .+\.md$"),
    "daily": re.compile(r"^\d{4}-\d{2}-\d{2}\.md$"),
    "week": re.compile(r"^\d{4}-W\d{2}\.md$"),
    "log": re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z0-9]+(?:-[a-z0-9]+)*\.md$"),
    "capture": re.compile(r"^\d{4}-\d{2}-\d{2} \d{4} .+\.md$"),
}
DATE_PREFIX_RE = re.compile(r"^\d{4}-\d{2}-\d{2}[ -]")
TASK_OPEN_RE = re.compile(r"^\s*[-*] \[ \] (.+)$", re.MULTILINE)
TASK_DONE_RE = re.compile(r"^\s*[-*] \[[xX]\] ", re.MULTILINE)


# ------------------------------------------------------------------ helpers

rel = linter.rel

# A single `check` reads every note for the linter, the structure pass, the link
# graph, and index regeneration. Caching the read and the parse turns four passes
# over the disk into one; the cache is invalidated on write, and the process is
# short-lived, so it cannot go stale.
_TEXT_CACHE: dict[str, str] = {}
_FM_CACHE: dict[str, object] = {}


def read_text(p: Path) -> str:
    key = str(p)
    cached = _TEXT_CACHE.get(key)
    if cached is None:
        try:
            cached = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            cached = ""
        _TEXT_CACHE[key] = cached
    return cached


def atomic_write(p: Path, text: str) -> None:
    """Write via a temp file in the same directory, then rename. A crash mid-write
    leaves the previous version intact rather than a truncated note."""
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(p)
    _TEXT_CACHE.pop(str(p), None)
    _FM_CACHE.pop(str(p), None)


def iter_notes(cfg: Config, dirs=None):
    yield from linter.iter_notes(cfg, dirs)


def parse_note(p: Path):
    key = str(p)
    cached = _FM_CACHE.get(key)
    if cached is None:
        cached = fmlib.parse(read_text(p))
        _FM_CACHE[key] = cached
    return cached


def fm_str(value) -> str:
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return str(value).strip('"') if value is not None else ""


def parse_date(value) -> dt.date | None:
    s = fmlib.unquote(str(value or "")).strip()
    try:
        return dt.date.fromisoformat(s[:10])
    except ValueError:
        return None


def days_since(value, today: dt.date) -> int | None:
    d = parse_date(value)
    return (today - d).days if d else None


# Most filesystems cap a single name at 255 bytes. Leave room for a date prefix, a
# collision suffix, the extension, and the `.tmp` an atomic write appends.
MAX_STEM_BYTES = 180


def slugify(title: str) -> str:
    """Make a filename from a title: drop link-unsafe characters, cap the length.

    The full, pretty title is never lost — it stays in `title:` and is added to
    `aliases:` whenever it differs, so `[[The Original Title]]` still resolves.
    """
    out = "".join("-" if ch in HARD_ILLEGAL else ("" if ch in SOFT_ILLEGAL else ch)
                  for ch in title)
    out = re.sub(r"-{2,}", "-", re.sub(r"\s+", " ", out)).strip(" .-")

    if len(out.encode("utf-8")) > MAX_STEM_BYTES:
        # Cut on a word boundary where possible, and never mid-character.
        truncated = out.encode("utf-8")[:MAX_STEM_BYTES].decode("utf-8", "ignore")
        head, _, _ = truncated.rpartition(" ")
        out = (head or truncated).strip(" .-")
    return out or "Untitled"


def next_free_path(p: Path, limit: int = 100) -> Path:
    if not p.exists():
        return p
    for n in range(2, limit):
        cand = p.with_name(f"{p.stem} {n}{p.suffix}")
        if not cand.exists():
            return cand
    raise SystemExit(f"too many files named like {p.name}")


def basename_index(cfg: Config) -> dict[str, list[Path]]:
    """Title (and alias) -> files. Wikilinks resolve by basename, never by path."""
    idx: dict[str, list[Path]] = defaultdict(list)
    for p in iter_notes(cfg):
        idx[p.stem].append(p)
        fm = parse_note(p)
        for alias in fmlib.as_list(fm.get("aliases")):
            idx[fmlib.unquote(str(alias))].append(p)
    return idx


def note_type(cfg: Config, p: Path):
    return cfg.type_for_path(rel(p))


# ------------------------------------------------------------------ structure

def structure_issues(cfg: Config) -> tuple[list[str], list[str]]:
    """Filenames and folders. Returns (errors, warnings)."""
    errors: list[str] = []
    warnings: list[str] = []
    for p in iter_notes(cfg):
        r = rel(p)
        if p.name.startswith("_") or cfg.is_generated(r):
            continue
        ntype = cfg.type_for_path(r)
        if ntype is None:
            continue

        bad_hard = {ch for ch in p.stem if ch in HARD_ILLEGAL}
        if bad_hard:
            errors.append(f"{r}: filename contains {''.join(sorted(bad_hard))!r} — breaks links")
        bad_soft = {ch for ch in p.stem if ch in SOFT_ILLEGAL}
        if bad_soft:
            warnings.append(
                f"{r}: filename contains {''.join(sorted(bad_soft))!r} — links to it may not "
                f"resolve (fix: vault.py rename)")

        pattern = ntype.filename
        variant = cfg.variant_for_path(r)
        if variant and variant.filename:
            pattern = variant.filename

        if pattern == "title":
            if DATE_PREFIX_RE.match(p.name):
                errors.append(f"{r}: evergreen {ntype.name} notes are not date-prefixed")
        elif pattern == "daily":
            if not (NAME_PATTERNS["daily"].match(p.name)
                    and re.match(rf"^{ntype.folder}/\d{{4}}/\d{{2}}/", r)):
                errors.append(f"{r}: expected {ntype.folder}/YYYY/MM/YYYY-MM-DD.md")
        elif pattern == "week":
            if not (NAME_PATTERNS["week"].match(p.name) or NAME_PATTERNS["dated"].match(p.name)):
                errors.append(f"{r}: expected 'YYYY-Www.md' or 'YYYY-MM-DD Title.md'")
        elif pattern == "capture":
            if not NAME_PATTERNS["capture"].match(p.name):
                warnings.append(f"{r}: captures are usually named 'YYYY-MM-DD HHmm Title.md'")
        elif pattern in NAME_PATTERNS:
            if not NAME_PATTERNS[pattern].match(p.name):
                hint = {"dated": "YYYY-MM-DD Title.md",
                        "log": "YYYY-MM-DD-<run_type>.md"}[pattern]
                errors.append(f"{r}: expected '{hint}'")

        # A type with variants must file its notes into one of them.
        if ntype.variants and variant is None and not cfg.is_generated(r):
            errors.append(f"{r}: {ntype.name} notes live in "
                          f"{ntype.folder}/<{'|'.join(ntype.subfolders)}>/")

        # Folders are a closed set (docs/routing.md): navigation is links, not
        # hierarchy. An undeclared subfolder is drift, and it is invisible until
        # someone wonders why half their projects are missing from a view.
        declared = set(ntype.subfolders)
        if ntype.archive_folder:
            declared.add(ntype.archive_folder.split("/", 1)[1])
        depth = r[len(ntype.folder) + 1:].count("/")
        if depth and ntype.filename != "daily":
            sub = r[len(ntype.folder) + 1:].rsplit("/", 1)[0]
            if sub not in declared:
                warnings.append(
                    f"{r}: {ntype.folder}/{sub}/ is not a declared subfolder. "
                    f"Folders are a closed set — link the note instead, or add a "
                    f"variant in config/lifeos.toml.")
    return errors, warnings


# ------------------------------------------------------------------ links

def link_report(cfg: Config):
    """Wikilinks that resolve to nothing. Returns (counter, examples)."""
    idx = basename_index(cfg)
    broken: Counter = Counter()
    where: dict[str, list[str]] = defaultdict(list)
    for p in iter_notes(cfg):
        r = rel(p)
        if r.startswith("logs/"):
            continue  # audit trail may reference notes that were later renamed
        text = fmlib.strip_code(read_text(p))
        for raw in set(fmlib.INLINE_LINK_RE.findall(text)):
            target = fmlib.link_target(raw)
            if not target or target in idx:
                continue
            broken[target] += 1
            if len(where[target]) < 3:
                where[target].append(r)
    return broken, where


def duplicate_basenames(cfg: Config) -> list[str]:
    """Two notes with the same filename make every `[[link]]` to them ambiguous:
    Obsidian silently picks one. Catch it at the moment it is created."""
    seen: dict[str, list[str]] = defaultdict(list)
    for p in iter_notes(cfg):
        # `_`-prefixed files are registries and generated indexes. Every folder has
        # its own `_index.md` by design; each carries a unique alias, and nothing
        # links to them by basename.
        if p.name.startswith("_"):
            continue
        seen[p.stem].append(rel(p))
    return [f"duplicate note name [[{stem}]] — links to it are ambiguous: "
            + ", ".join(sorted(paths))
            for stem, paths in sorted(seen.items()) if len(paths) > 1]


def source_link_issues(cfg: Config) -> tuple[list[str], list[str]]:
    """Every wiki `sources:` entry must resolve to a note under the source folder.
    Provenance is the wiki's whole claim to trustworthiness, so a source pointing at
    a non-source note is an error, while one pointing at nothing is a review queue."""
    stype = cfg.types.get("source")
    wtype = cfg.types.get("wiki")
    if not stype or not wtype:
        return [], []
    idx = basename_index(cfg)
    errors: list[str] = []
    dangling: list[str] = []
    for p in iter_notes(cfg, [wtype.folder]):
        r = rel(p)
        if cfg.is_generated(r) or p.name.startswith("_"):
            continue
        for entry in fmlib.as_list(parse_note(p).get("sources")):
            target = fmlib.link_target(str(entry))
            hits = idx.get(target)
            if not hits:
                dangling.append(f"{r}: sources entry [[{target}]] resolves to nothing")
            elif not any(rel(h).startswith(stype.folder + "/") for h in hits):
                errors.append(f"{r}: sources entry [[{target}]] is not under {stype.folder}/")
    return errors, dangling


# ------------------------------------------------------------------ generated views

def _index_frontmatter(cfg: Config, title: str, created: str, updated: str) -> list[str]:
    # Every generated index is named `_index.md` in its own folder, which is the
    # Obsidian convention for "sorts first" — but it makes `[[_index]]` ambiguous.
    # The alias gives each one a unique, linkable name.
    return ["---", "type: wiki", f'title: "{title}"', f'aliases: ["{title}"]',
            f'created: "{created}"', f'updated: "{updated}"',
            f"domain: {cfg.meta_domain}", "tags: [index]", "---", GENERATED_MARK, ""]


def _collect(cfg: Config, folder: str, skip_generated: bool = True):
    for p in iter_notes(cfg, [folder]):
        r = rel(p)
        if p.name.startswith("_") or (skip_generated and cfg.is_generated(r)):
            continue
        yield p, parse_note(p)


def gen_projects_index(cfg: Config, today: dt.date) -> str:
    ptype = cfg.types["project"]
    statuses = ptype.enums.get("status", ["active"])
    rows: dict[str, list] = {s: [] for s in statuses}
    latest = ""
    for p, fm in _collect(cfg, ptype.folder):
        status = fm_str(fm.get("status")) or statuses[0]
        rows.setdefault(status, []).append((p.stem, fm))
        latest = max(latest, fm_str(fm.get("updated")))

    lines = _index_frontmatter(cfg, "Projects Index", "2026-01-01",
                               latest or today.isoformat())
    lines += ["# Projects Index", "",
              "One line per project, grouped by status. Live view: `bases/projects.base`.",
              f"Lifecycle: {' → '.join(statuses)} (docs/routing.md).", ""]
    for status in statuses:
        items = sorted(rows.get(status, []),
                       key=lambda t: (fm_str(t[1].get("updated")), t[0]), reverse=True)
        lines += [f"## {status.title()} ({len(items)})", ""]
        if not items:
            lines.append("- (none)")
        for stem, fm in items:
            question = fm_str(fm.get("question")).strip()
            meta = " · ".join(x for x in (
                fm_str(fm.get("domain")), fm_str(fm.get("kind")),
                f"updated {fm_str(fm.get('updated'))}" if fm.get("updated") else "") if x)
            lines.append(f"- [[{stem}]] — {question}" + (f" _({meta})_" if meta else ""))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _wiki_hook(fm, body: str) -> str:
    """One line describing a wiki page: its first real sentence, capped."""
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "-", ">", "|", "<!--", "```")):
            continue
        s = re.sub(r"\[\[([^\[\]|]+)(?:\|[^\[\]]*)?\]\]", r"\1", s)
        s = re.sub(r"[*_`]", "", s)
        return (s[:117] + "…") if len(s) > 118 else s
    return ""


def gen_wiki_domain_pages(cfg: Config, today: dt.date) -> dict[str, str]:
    """One router page per domain. Splitting the router up front is the scaling
    migration the source vault deferred: at 2,000 pages a single index becomes too
    large to read, and by then it is load-bearing."""
    wtype = cfg.types["wiki"]
    by_domain: dict[str, list] = defaultdict(list)
    for p, fm in _collect(cfg, wtype.folder):
        r = rel(p)
        if r.startswith(cfg.wiki_domain_dir + "/"):
            continue
        domain = fm_str(fm.get("domain")) or "unsorted"
        by_domain[domain].append((p, fm))

    out: dict[str, str] = {}
    for domain in cfg.domains:
        items = sorted(by_domain.get(domain, []), key=lambda t: t[0].stem.lower())
        latest = max((fm_str(fm.get("updated")) for _, fm in items), default="")
        lines = _index_frontmatter(cfg, f"{domain.title()} Domain", "2026-01-01",
                                   latest or today.isoformat())
        lines += [f"# {domain.title()}", "",
                  f"Every wiki page with `domain: {domain}`. Regenerated by `vault.py index`.", ""]
        # Prose above the marker survives regeneration; see _preserve_prose.
        lines += ["<!-- PROSE:START --><!-- PROSE:END -->", "",
                  f"## Pages ({len(items)})", ""]
        if not items:
            lines.append("- (none yet)")
        for p, fm in items:
            hook = _wiki_hook(fm, fmlib.parse(read_text(p)).body)
            lines.append(f"- [[{p.stem}]]" + (f" — {hook}" if hook else ""))
        out[f"{cfg.wiki_domain_dir}/{domain}.md"] = "\n".join(lines).rstrip() + "\n"
    return out


def gen_wiki_index(cfg: Config, today: dt.date) -> str:
    """A dispatcher, not a catalogue. Agents grep this, then open one domain page,
    or skip it entirely and use `retrieve.py`."""
    wtype = cfg.types["wiki"]
    counts: Counter = Counter()
    recent: list[tuple[str, str]] = []
    for p, fm in _collect(cfg, wtype.folder):
        r = rel(p)
        if r.startswith(cfg.wiki_domain_dir + "/"):
            continue
        counts[fm_str(fm.get("domain")) or "unsorted"] += 1
        recent.append((fm_str(fm.get("updated")), p.stem))
    total = sum(counts.values())
    lines = _index_frontmatter(cfg, "Wiki Index", "2026-01-01", today.isoformat())
    lines += [
        "# Wiki Index", "",
        f"{total} compiled pages. This file is a **router**, not a catalogue.", "",
        "- Looking for a topic? `python3 scripts/retrieve.py \"<query>\"` searches page text.",
        "- Browsing by area of life? Open the domain page below.",
        "- Need an exact title? `grep -r '^title:' wiki/`.", "",
        "## Domains", "",
    ]
    for domain in cfg.domains:
        n = counts.get(domain, 0)
        lines.append(f"- [[{domain}]] — {n} page{'s' if n != 1 else ''}")
    unsorted = counts.get("unsorted", 0)
    if unsorted:
        lines.append(f"- _(unsorted: {unsorted} page(s) with no domain — `vault doctor` lists them)_")
    lines += ["", "## Recently updated", ""]
    for _, stem in sorted((r for r in recent if r[0]), reverse=True)[:15]:
        lines.append(f"- [[{stem}]]")
    if not recent:
        lines.append("- (none yet)")
    return "\n".join(lines).rstrip() + "\n"


def gen_home(cfg: Config, today: dt.date) -> str:
    """The landing page. Deliberately small and stable: counts, what needs attention,
    and links to the live Base views. It is a signpost, not a data dump."""
    st = collect_status(cfg, today)
    lines = ["---", "type: wiki", 'title: "Home"', 'created: "2026-01-01"',
             f'updated: "{today.isoformat()}"', f"domain: {cfg.meta_domain}",
             "tags: [index]", "---", GENERATED_MARK, "",
             f"# {cfg.name}", "",
             f"_Regenerated {today.isoformat()} by `python3 scripts/vault.py index`._", "",
             "## Needs attention", ""]

    bullets = []
    if st["inbox"]["count"]:
        oldest = st["inbox"]["oldest_days"]
        bullets.append(f"**Inbox:** {st['inbox']['count']} item(s)"
                       + (f", oldest {oldest}d" if oldest is not None else ""))
    for label, items in (("Stale active projects", st["projects"]["stale"]),
                         ("Old ideas", st["projects"]["old_ideas"]),
                         ("Projects awaiting archive", st["projects"]["awaiting_archive"]),
                         ("Decisions due for outcome", st["decisions"]["due"])):
        if items:
            bullets.append(f"**{label}:** " + ", ".join(f"[[{i}]]" for i in items[:6])
                           + (" …" if len(items) > 6 else ""))
    if st["tasks"]["open"]:
        bullets.append(f"**Open tasks:** {st['tasks']['open']} across "
                       f"{st['tasks']['notes']} note(s) — `vault.py tasks`")
    lines += [f"- {b}" for b in bullets] or ["- Nothing. Good."]

    lines += ["", "## Counts", "", "| What | Count |", "|---|---|"]
    for label, value in (("Projects active", st["projects"]["by_status"].get("active", 0)),
                         ("Projects total", sum(st["projects"]["by_status"].values())),
                         ("Areas active", st["areas"]["active"]),
                         ("Wiki pages", st["wiki"]["total"]),
                         ("Sources", st["sources"]["total"]),
                         ("People", st["people"]), ("Meetings", st["meetings"])):
        lines.append(f"| {label} | {value} |")

    lines += ["", "## Views", "",
              "Open these in Obsidian for live tables:", "",
              "- `bases/attention.base` — everything waiting on you",
              "- `bases/projects.base` — projects by status",
              "- `bases/knowledge.base` — wiki pages and sources",
              "- `bases/people.base` — people and meetings", "",
              "## Indexes", "",
              "- [[Projects Index]] · every project, grouped by status",
              "- [[Wiki Index]] · the router into compiled knowledge", "",
              "## Start here", "",
              "- `AGENTS.md` — the map, the invariants, the commands",
              "- `docs/daily-guide.md` — how to actually use this day to day",
              "- `docs/routing.md` — where does this note go?", ""]
    return "\n".join(lines).rstrip() + "\n"


PROSE_RE = re.compile(r"<!-- PROSE:START -->(.*?)<!-- PROSE:END -->", re.DOTALL)


def _preserve_prose(old: str, new: str) -> str:
    """Carry a human-written preamble across regeneration. Generated files are
    otherwise fully owned by the generator; this is the one sanctioned exception,
    and it is explicitly delimited so nobody has to guess."""
    m_old, m_new = PROSE_RE.search(old), PROSE_RE.search(new)
    if not (m_old and m_new) or not m_old.group(1).strip():
        return new
    return new[:m_new.start(1)] + m_old.group(1) + new[m_new.end(1):]


def generated_content(cfg: Config, today: dt.date) -> dict[str, str]:
    out = {"projects/_index.md": gen_projects_index(cfg, today),
           "wiki/_index.md": gen_wiki_index(cfg, today)}
    out.update(gen_wiki_domain_pages(cfg, today))
    out["Home.md"] = gen_home(cfg, today)          # last: reads the others' inputs
    return out


def orphaned_generated(cfg: Config, wanted: set[str]) -> tuple[list[str], list[str]]:
    """Generated files that no longer correspond to anything in the config.

    Removing a domain should remove its router page — otherwise the vault keeps a
    page for a category that no longer exists. Only files carrying the generated
    marker are eligible: a file someone hand-wrote into that folder is theirs, and
    deleting it because a config value changed would be the kind of surprise this
    system exists to avoid.

    Returns (removable, foreign).
    """
    removable, foreign = [], []
    domain_dir = VAULT / cfg.wiki_domain_dir
    if not domain_dir.is_dir():
        return removable, foreign
    for p in sorted(domain_dir.glob("*.md")):
        relpath = rel(p)
        if relpath in wanted or p.name.startswith("_"):
            continue
        (removable if GENERATED_MARK in read_text(p) else foreign).append(relpath)
    return removable, foreign


def cmd_index(cfg: Config, args) -> int:
    today = dt.date.today()
    content_by_path = generated_content(cfg, today)
    changed = []
    for relpath, content in content_by_path.items():
        p = VAULT / relpath
        old = read_text(p) if p.exists() else ""
        content = _preserve_prose(old, content)
        if old != content:
            if not args.check:
                atomic_write(p, content)
            changed.append(relpath)

    removable, foreign = orphaned_generated(cfg, set(content_by_path))
    if args.check:
        for c in changed:
            print(f"STALE  {c}")
        for c in removable:
            print(f"ORPHAN {c}: no longer in the config — run `vault.py index`")
        return 1 if (changed or removable) else 0

    for relpath in removable:
        (VAULT / relpath).unlink()
    for relpath in foreign:
        print(f"WARN   {relpath} is not a current domain page but was not generated "
              f"— left alone. Move or delete it by hand.")
    if not args.quiet:
        parts = []
        if changed:
            parts.append(f"{len(changed)} regenerated: " + ", ".join(changed))
        if removable:
            parts.append(f"{len(removable)} removed: " + ", ".join(removable))
        print("index: " + ("; ".join(parts) if parts else "all current"))
    return 0


def generated_stale(cfg: Config, today: dt.date) -> list[str]:
    content_by_path = generated_content(cfg, today)
    stale = []
    for relpath, content in content_by_path.items():
        p = VAULT / relpath
        old = read_text(p) if p.exists() else ""
        if old != _preserve_prose(old, content):
            stale.append(f"{relpath}: stale — run `python3 scripts/vault.py index`")
    removable, _ = orphaned_generated(cfg, set(content_by_path))
    stale += [f"{r}: generated page for a domain that no longer exists — "
              f"run `python3 scripts/vault.py index`" for r in removable]
    return stale


