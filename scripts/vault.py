def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="vault.py", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("check", help="structure + schema + generated freshness")
    s.add_argument("--strict", action="store_true", help="treat broken links as errors")
    s = sub.add_parser("lint", help="frontmatter only")
    s.add_argument("paths", nargs="*")
    s = sub.add_parser("links", help="broken wikilinks")
    s.add_argument("--wanted", action="store_true", help="most-linked missing pages")
    s.add_argument("--top", type=int, default=30)
    s = sub.add_parser("index", help="regenerate generated views")
    s.add_argument("--check", action="store_true", help="report staleness, write nothing")
    s.add_argument("--quiet", action="store_true")
    s = sub.add_parser("status", help="what needs attention")
    s.add_argument("--json", action="store_true")
    s = sub.add_parser("tasks", help="open checkboxes")
    s.add_argument("--all", action="store_true", help="include old daily notes")
    s.add_argument("--json", action="store_true")
    s = sub.add_parser("doctor", help="check + advisory report")
    s.add_argument("--strict", action="store_true")
    s = sub.add_parser("new", help="create a note with correct path and frontmatter")
    s.add_argument("type")
    s.add_argument("title", nargs="?")
    s.add_argument("--set", action="append", metavar="KEY=VALUE")
    s.add_argument("--body", help="text to append below the frontmatter")
    s.add_argument("--date", help="YYYY-MM-DD (default: today)")
    s.add_argument("--force", action="store_true")
    s = sub.add_parser("rename", help="rename one note and rewrite links to it")
    s.add_argument("path")
    s.add_argument("new_title")
    s.add_argument("--dry-run", action="store_true")
    s.add_argument("--no-alias", action="store_true", help="do not keep the old title as an alias")
    s.add_argument("--force", action="store_true")
    s = sub.add_parser("docs", help="regenerate docs/schema.md from config")
    s.add_argument("--check", action="store_true")

    args = ap.parse_args(argv)
    try:
        cfg = load()
    except ConfigError as e:
        print(f"ERROR  {e}", file=sys.stderr)
        return 2

    handlers = {"check": cmd_check, "lint": cmd_lint, "links": cmd_links, "index": cmd_index,
                "status": cmd_status, "tasks": cmd_tasks, "doctor": cmd_doctor,
                "new": cmd_new, "rename": cmd_rename, "docs": cmd_docs}
    return handlers[args.cmd](cfg, args)


if __name__ == "__main__":
    sys.exit(main())
